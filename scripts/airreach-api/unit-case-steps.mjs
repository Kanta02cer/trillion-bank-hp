// 案件の5段階（assets/js/airreach-case-steps.js）：保存データから段階の状態と「次にやること」を決める。架空のデータだけ
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ctx = { window: {}, console, URL, JSON, Math, Date };
vm.createContext(ctx);
for (const f of ['airreach-ai3.js', 'airreach-case-steps.js']) vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/js', f), 'utf8'), ctx);
const K = ctx.window.AirReachCaseSteps;
let pass = 0, fail = 0;
const t = (n, ok, got) => { if (ok) { pass++; console.log('PASS', n); } else { fail++; console.log('FAIL', n, got === undefined ? '' : JSON.stringify(got).slice(0, 300)); } };
const states = (r) => r.steps.map((s) => s.state[0]).join('');
const mf = (o) => ({ 'MANIFEST.json': JSON.stringify(o) });
const job = (o) => Object.assign({ url: 'https://sample-salon.example/', files: mf({ faq_counts: { pending_approval: 2 } }) }, o);
const ans = (n) => Array.from({ length: n }, (_, i) => ({ prompt: 'q' + i, engine: 'google_aio', status: 'ok', mentioned: i < 2 ? 1 : 0, conditions: { engine: 'google_aio', search: true, location: 'JP', model: 'm' } }));
const run = (at, n) => ({ id: at, created_at: at, measured_on: at.slice(0, 10), summary: { answers: ans(n) } });
const H = { studioHref: '/airreach/studio/?c=1', runsHref: '#/c/1/runs' };

let r = K.compute(Object.assign({ workspace: null, runs: [] }, H));
t('何もない：①が今・次は「サイトを調べる」', states(r) === 'ctttt' && r.next.title === 'サイトを調べる' && /#start$/.test(r.next.href), [states(r), r.next]);
r = K.compute(Object.assign({ workspace: { orch: { lastJob: job({}) } }, runs: [] }, H));
t('分析あり・未確定：次は「会社・サービスを確定する」', states(r) === 'ctttt' && r.next.title === '会社・サービスを確定する' && /#generator$/.test(r.next.href));
const ent = { company: '株式会社サンプル', service: '縮毛矯正', at: '2026-10-07T01:00:00Z' };
r = K.compute(Object.assign({ workspace: { orch: { lastJob: job({ confirm: { entity: ent } }) } }, runs: [] }, H));
t('確定済み・計測なし：②が今', states(r) === 'dcttt' && /計測/.test(r.next.title) && /#hack2$/.test(r.next.href));
t('①の説明に確定日と会社・サービス', /10\/7：株式会社サンプル・縮毛矯正/.test(r.steps[0].detail), r.steps[0].detail);
r = K.compute(Object.assign({ workspace: { orch: { lastJob: job({ confirm: { entity: ent } }) } }, runs: [run('2026-10-07T02:00:00Z', 9)] }, H));
t('導入前の計測あり：③が今・承認待ち2問を次に', states(r) === 'ddctt' && /2問を承認/.test(r.next.title), [states(r), r.next.title]);
t('②の説明に AI による概要の X/N', /AI による概要 2 \/ 9回/.test(r.steps[1].detail), r.steps[1].detail);
r = K.compute(Object.assign({ workspace: { orch: { lastJob: job({ confirm: { entity: ent }, zipped: { at: '2026-10-08T00:00:00Z', version: '1.3.0', draft: true } }) } }, runs: [run('2026-10-07T02:00:00Z', 9)] }, H));
t('下書きの ZIP（-DRAFT）では③は済まない', states(r) === 'ddctt');
const zj = job({ confirm: { entity: ent }, zipped: { at: '2026-10-08T00:00:00Z', version: '1.3.0', draft: false } });
r = K.compute(Object.assign({ workspace: { orch: { lastJob: zj } }, runs: [run('2026-10-07T02:00:00Z', 9)] }, H));
t('正式な ZIP を作った：④が今（入れたか確かめる）', states(r) === 'dddct' && /入ったか/.test(r.next.title) && /ZIP v1\.3\.0/.test(r.steps[2].detail), [states(r), r.steps[2].detail]);
r = K.compute(Object.assign({ workspace: { orch: { lastJob: zj } }, runs: [run('2026-10-07T02:00:00Z', 9), run('2026-10-28T02:00:00Z', 9)] }, H));
t('導入後の計測あり：全部済み・次は「次の改善」', states(r) === 'ddddd' && r.next.title === '次の改善を始める', [states(r), r.next.title]);
t('⑤の説明に導入後の計測の回数', /導入後の計測 1回/.test(r.steps[4].detail));
r = K.compute(Object.assign({ workspace: { orch: { lastJob: zj } }, runs: [run('2026-10-28T02:00:00Z', 9)] }, H));
t('ZIP の前の計測が無ければ、導入後の計測しかなくても②は「まだ」', r.steps[1].state !== 'done' && r.steps[4].state !== 'done', states(r));
r = K.compute(Object.assign({ workspace: { orch: { lastJob: job({ confirm: { entity: ent } }) } }, runs: [{ id: 'x', created_at: '2026-10-07T00:00:00Z', summary: { by: [] } }] }, H));
t('回答の記録が無い古い計測は導入前に数えない', r.steps[1].state === 'current');
const html = K.cardHtml(K.compute(Object.assign({ workspace: { orch: { lastJob: job({ confirm: { entity: { company: '<b>x</b>', service: 'y', at: '2026-10-07T01:00:00Z' } } }) } }, runs: [] }, H)));
t('描画：次にやること・5段階・いまの段階に aria-current・エスケープ', /次にやること/.test(html) && (html.match(/class="acs-step is-/g) || []).length === 5 && /aria-current="step"/.test(html) && !html.includes('<b>x</b>'));
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
